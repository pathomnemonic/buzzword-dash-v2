import json,re,sys,os
cards=json.load(open('/tmp/mm_raw/stage.json'))
ww=json.load(open('ww.json')) if os.path.exists('ww.json') else {}
fix=json.load(open('fixes.json')) if os.path.exists('fixes.json') else {}
def clues(h):
    h=h.strip()
    parts=[x.strip() for x in re.split(r':\s+|;\s+|,\s+(?![^()]*\))',h) if x.strip()]
    if len(parts)>3:
        parts=[parts[0],parts[1],' '.join(parts[2:])]
    return parts
out=[];drop=[]
for c in cards:
    f=fix.get(str(c['n']),{})
    if f.get('drop'): drop.append((c['n'],f['drop'])); continue
    if c['evsup']<0.5 and 'ev' not in f: drop.append((c['n'],'no evidence')); continue
    bw=f.get('bw') or clues(c['hint'])
    ans=f.get('ans',c['ans']); d=f.get('d',c['d'])
    card=dict(subj=c['subj'],bw=bw,ans=ans,d=d,tp=f.get('tp',c['tp']),
      ww=ww.get(str(c['n'])) or {d[0]:'Different from the answer here.',d[1]:'Different from the answer here.'},
      source_ref=c['id'],evidence=f.get('ev',c['ev']),
      tags=['medmcqa',c['ds'].lower().replace(' & ','-').replace(' ','-')],
      exams=[],questionType=c['qt'],baseDifficulty=2,_n=c['n'])
    out.append(card)
deck=dict(format=1,id='medmcqa',title='MedMCQA essentials',
 source='MedMCQA (Pal et al., CHIL 2022)',
 licence=dict(name='Apache-2.0 (as listed on the dataset card)',url='https://www.apache.org/licenses/LICENSE-2.0'),
 attribution='Adapted from MedMCQA: A Large-scale Multi-Subject Multi-Choice Dataset for Medical domain Question Answering. Pal A, Umapathi LK, Sankarasubbu M. Proceedings of the Conference on Health, Inference, and Learning (CHIL), PMLR 174, 2022. Dataset openlifescienceai/medmcqa on Hugging Face, licence Apache-2.0 as listed on the dataset card. Questions are exam questions compiled from Indian medical entrance exams, rewritten into runner format by an AI and checked automatically; provenance of the original questions is unclear and the cards have not been verified for exam accuracy by a clinician.',
 url='https://huggingface.co/datasets/openlifescienceai/medmcqa',
 author='Pal, Umapathi and Sankarasubbu (MedMCQA); runner cards generated by Dx Dash',
 version='1.0.0',count=len(out),cards=out)
json.dump(deck,open('/tmp/mm_raw/deck_work.json','w'),indent=1)
json.dump(drop,open('/tmp/mm_raw/drops.json','w'))
print(len(out),'cards',len(drop),'dropped before check')
