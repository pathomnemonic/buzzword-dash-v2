#!/usr/bin/env node
/**
 * content-audit.mjs - regenerates docs/CONTENT-STATS.md
 *
 * Per-subject statistics for the built-in deck: counts by subject, difficulty,
 * exam tag and question type, cards with no pearls, duplicate answers and
 * clue-leak warnings. (tools/audit-content.mjs prints a console quality report;
 * this tool writes the committed Markdown stats file.)
 *
 * Usage:
 *   node tools/content-audit.mjs           write docs/CONTENT-STATS.md
 *   node tools/content-audit.mjs --stdout  print instead of writing
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { CARDS, SUBJECTS, EXAM_FILTERS, QUESTION_TYPES, getLoadReport } from '../js/cards.js';
import { deckGenericWords, strictLeakReport, answerKey } from '../js/cardleaks.js';

const toStdout = process.argv.includes('--stdout');
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'CONTENT-STATS.md');

const tally = (cards, fn) => {
  const m = new Map();
  cards.forEach((c) => { const k = fn(c); m.set(k, (m.get(k) || 0) + 1); });
  return m;
};
const table = (head, rows) =>
  ['| ' + head.join(' | ') + ' |', '|' + head.map((h, i) => (i ? '---:' : '---')).join('|') + '|']
    .concat(rows.map((r) => '| ' + r.join(' | ') + ' |')).join('\n');

const generic = deckGenericWords(CARDS.map((c) => c.ans));
const bySubject = new Map(SUBJECTS.map((s) => [s, []]));
CARDS.forEach((c) => { if (!bySubject.has(c.subj)) bySubject.set(c.subj, []); bySubject.get(c.subj).push(c); });

const noPearls = CARDS.filter((c) => !c.pearls || !c.pearls.length);
const dupGroups = new Map();
CARDS.forEach((c) => { const k = answerKey(c.ans); if (!dupGroups.has(k)) dupGroups.set(k, []); dupGroups.get(k).push(c); });
const dups = [...dupGroups.values()].filter((g) => g.length > 1);
const leaks = [];
CARDS.forEach((c) => strictLeakReport(c, generic).leaking.forEach((l) => leaks.push(c.id + ' [' + c.ans + '] "' + l.clue + '" - ' + l.why)));
const report = getLoadReport();

const L = [];
L.push('# Content stats', '',
  '_Generated by `npm run audit:content-stats` (tools/content-audit.mjs). Do not edit by hand._', '',
  '- Total cards: **' + CARDS.length + '**',
  '- Cards with no pearls: **' + noPearls.length + '**',
  '- Duplicate answer groups: **' + dups.length + '**',
  '- Strict clue-leak warnings: **' + leaks.length + '**',
  '- Loader: ' + report.loaded + ' loaded, ' + report.dropped.length + ' dropped, ' + report.warnings.length + ' warnings', '');

L.push('## Per subject', '');
L.push(table(['Subject', 'Cards', 'D1', 'D2', 'D3', 'No pearls', 'Dup answers', 'Leaks'],
  [...bySubject.entries()].map(([s, cs]) => {
    const d = tally(cs, (c) => c.baseDifficulty);
    const ids = new Set(cs.map((c) => c.id));
    const dupN = dups.filter((g) => g.some((c) => ids.has(c.id))).length;
    const leakN = leaks.filter((l) => ids.has(l.split(' ')[0])).length;
    return [s, cs.length, d.get(1) || 0, d.get(2) || 0, d.get(3) || 0, cs.filter((c) => !c.pearls || !c.pearls.length).length, dupN, leakN];
  }).concat([['**Total**', CARDS.length, ...[1, 2, 3].map((n) => CARDS.filter((c) => c.baseDifficulty === n).length), noPearls.length, dups.length, leaks.length]])), '');

L.push('## Exam tags', '');
L.push(table(['Subject'].concat(EXAM_FILTERS), [...bySubject.entries()].map(([s, cs]) =>
  [s].concat(EXAM_FILTERS.map((e) => cs.filter((c) => (c.exams || []).includes(e)).length)))
  .concat([['**Total**'].concat(EXAM_FILTERS.map((e) => CARDS.filter((c) => (c.exams || []).includes(e)).length))])), '');

L.push('## Question types', '');
L.push(table(['Subject'].concat(QUESTION_TYPES), [...bySubject.entries()].map(([s, cs]) =>
  [s].concat(QUESTION_TYPES.map((q) => cs.filter((c) => c.questionType === q).length)))
  .concat([['**Total**'].concat(QUESTION_TYPES.map((q) => CARDS.filter((c) => c.questionType === q).length))])), '');

L.push('## Cards with no pearls', '');
L.push(noPearls.length ? noPearls.map((c) => '- ' + c.id + ' ' + c.ans).join('\n') : 'None.', '');
L.push('## Duplicate answers', '');
L.push(dups.length ? dups.map((g) => '- ' + g.map((c) => c.id).join(', ') + ': ' + g[0].ans).join('\n') : 'None.', '');
L.push('## Leak warnings', '');
L.push(leaks.length ? leaks.map((l) => '- ' + l).join('\n') : 'None.', '');
if (report.warnings.length) {
  L.push('## Loader warnings', '', report.warnings.map((w) => '- ' + w).join('\n'), '');
}
const text = L.join('\n');
if (toStdout) process.stdout.write(text); else { writeFileSync(out, text); console.log('wrote ' + out); }
