/**
 * pick-free-cards.mjs — chooses the 300 cards every player gets free: 20 from each of the 15 subjects, spread over
 * the difficulty levels, the question types and the exams, so the free library is a fair taste of the whole bank rather
 * than the first 300 cards. Writes js/freecards.js. Run once; the list is then fixed (so a card never moves in or out
 * of the free set because the bank was edited). `npm run free:cards -- --check` verifies the committed list.
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { CARDS } from '../js/cards.js';
import { SUBJECTS } from '../js/cardmeta.js';

var PER_SUBJECT = 20;

function h(s) { var x = 2166136261; for (var i = 0; i < s.length; i++) { x ^= s.charCodeAt(i); x = Math.imul(x, 16777619) >>> 0; } return x; }

export function pickFreeCards(cards, subjects, per) {
  var out = {};
  subjects.forEach(function (subj) {
    var pool = cards.filter(function (c) { return c.subj === subj && (!Array.isArray(c.enabledModes) || !c.enabledModes.length || c.enabledModes.indexOf('study') >= 0 || c.enabledModes.indexOf('endless') >= 0); });
    pool.sort(function (a, b) { return h(a.id) - h(b.id); }); // a fixed shuffle
    var byLevel = {};
    pool.forEach(function (c) { var k = String(c.baseDifficulty || 2); (byLevel[k] = byLevel[k] || []).push(c); });
    var levels = Object.keys(byLevel).sort();
    var chosen = [];
    var usedTypes = {};
    var guard = 0;
    while (chosen.length < per && guard++ < 1000) {
      var added = false;
      for (var i = 0; i < levels.length && chosen.length < per; i++) {
        var list = byLevel[levels[i]];
        // prefer a question type not used much yet, so the set is varied
        var at = -1; var best = 1e9;
        for (var j = 0; j < Math.min(list.length, 12); j++) { var u = usedTypes[list[j].questionType] || 0; if (u < best) { best = u; at = j; } }
        if (at < 0) continue;
        var card = list.splice(at, 1)[0];
        chosen.push(card.id);
        usedTypes[card.questionType] = (usedTypes[card.questionType] || 0) + 1;
        added = true;
      }
      if (!added) break;
    }
    out[subj] = chosen.sort();
  });
  return out;
}

if (process.argv[1] && process.argv[1].endsWith('pick-free-cards.mjs')) {
  var picked = pickFreeCards(CARDS, SUBJECTS, PER_SUBJECT);
  var text = '/**\n * freecards.js — the 300 cards free players get (20 per subject, spread over difficulty and question type).\n * Generated by tools/pick-free-cards.mjs. The list is fixed: do not edit by hand and do not regenerate after launch,\n * or cards would move in and out of the free set.\n */\n\nexport var FREE_CARD_IDS_BY_SUBJECT = ' + JSON.stringify(picked, null, 1).replace(/\n\s+"/g, '\n  "').replace(/\[\n\s+/g, '[').replace(/",\n\s+"(?=[a-z]{1,3}\d)/g, '", "') + ';\n\nexport var FREE_CARD_IDS = new Set([].concat.apply([], Object.keys(FREE_CARD_IDS_BY_SUBJECT).map(function (k) { return FREE_CARD_IDS_BY_SUBJECT[k]; })));\n';
  if (process.argv.indexOf('--check') >= 0) {
    var current = readFileSync(new URL('../js/freecards.js', import.meta.url), 'utf8');
    console.log(current === text ? 'free card list is up to date' : 'free card list differs (do not regenerate after launch)');
    process.exit(current === text ? 0 : 1);
  }
  writeFileSync(new URL('../js/freecards.js', import.meta.url), text);
  var n = Object.keys(picked).reduce(function (a, k) { return a + picked[k].length; }, 0);
  console.log('wrote js/freecards.js with ' + n + ' cards');
}
